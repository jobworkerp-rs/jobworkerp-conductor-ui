#!/usr/bin/env bash
# Usage: sync-protos.sh
#
# Copies the protobuf definitions this UI talks to into proto/, laid out by
# package (proto/jobworkerp_conductor/..., proto/jobworkerp/...), and records
# where each came from in proto/VERSIONS. scripts/gen-proto.sh reads only this
# output, so switching the source (e.g. to a future public proto repository
# used as a submodule) only changes this script.
#
# Sources default to the pinned public tags below. Override per package:
#   CONDUCTOR_PROTO_DIR / JOBWORKERP_PROTO_DIR   a local directory containing
#                                                the package directory
#   CONDUCTOR_PROTO_REPO / CONDUCTOR_PROTO_REF   another git remote / ref
#   JOBWORKERP_PROTO_REPO / JOBWORKERP_PROTO_REF
#   PROTO_OUT                                    output directory (default proto/)
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=lib/common.sh
source "${SCRIPT_DIR}/lib/common.sh"
# shellcheck source=lib/conductor-release.sh
source "${SCRIPT_DIR}/lib/conductor-release.sh"
ROOT_DIR=$(cd "${SCRIPT_DIR}/.." && pwd)

CONDUCTOR_PROTO_REPO=${CONDUCTOR_PROTO_REPO:-https://github.com/jobworkerp-rs/jobworkerp-conductor.git}
CONDUCTOR_PROTO_REF=${CONDUCTOR_PROTO_REF:-${CONDUCTOR_RELEASE}}
JOBWORKERP_PROTO_REPO=${JOBWORKERP_PROTO_REPO:-https://github.com/jobworkerp-rs/jobworkerp-rs.git}
JOBWORKERP_PROTO_REF=${JOBWORKERP_PROTO_REF:-v0.25.0}
PROTO_OUT=${PROTO_OUT:-${ROOT_DIR}/proto}

work=$(mktemp -d)
trap 'rm -rf "${work}"' EXIT
staging="${work}/staging"
mkdir -p "${staging}"
: >"${work}/versions"

# fetch <package> <local-dir> <repo> <ref>: stage proto/<package> and append
# "<package> <repo|local> <ref|path> <commit|->" to the version record.
fetch() {
  local package=$1 local_dir=$2 repo=$3 ref=$4 src commit
  if [[ -n "${local_dir}" ]]; then
    src=${local_dir}
    [[ -d "${src}/${package}" ]] || die "${src} has no ${package}/ directory"
    printf '%s local %s -\n' "${package}" "${src}" >>"${work}/versions"
  else
    local checkout="${work}/checkout-${package}"
    git -c advice.detachedHead=false clone --quiet --depth 1 --branch "${ref}" --filter=blob:none --sparse "${repo}" "${checkout}" \
      || die "cannot clone ${repo} at ${ref}"
    git -C "${checkout}" sparse-checkout set "proto/protobuf/${package}"
    src="${checkout}/proto/protobuf"
    [[ -d "${src}/${package}" ]] || die "${repo}@${ref} has no proto/protobuf/${package}/"
    commit=$(git -C "${checkout}" rev-parse HEAD)
    printf '%s %s %s %s\n' "${package}" "${repo}" "${ref}" "${commit}" >>"${work}/versions"
  fi
  cp -R "${src}/${package}" "${staging}/${package}"
}

fetch jobworkerp_conductor "${CONDUCTOR_PROTO_DIR-}" "${CONDUCTOR_PROTO_REPO}" "${CONDUCTOR_PROTO_REF}"
fetch jobworkerp "${JOBWORKERP_PROTO_DIR-}" "${JOBWORKERP_PROTO_REPO}" "${JOBWORKERP_PROTO_REF}"

# Replace the output only after every source was fetched, so a failed sync
# leaves the previous tree intact.
mkdir -p "${PROTO_OUT}"
for package in jobworkerp_conductor jobworkerp; do
  rm -rf "${PROTO_OUT:?}/${package}"
  cp -R "${staging}/${package}" "${PROTO_OUT}/${package}"
done
{
  echo "# Generated by scripts/sync-protos.sh; do not edit."
  echo "# <package> <repository|local> <ref|path> <commit|->"
  cat "${work}/versions"
} >"${PROTO_OUT}/VERSIONS"

echo "synced protos into ${PROTO_OUT}"
