#!/bin/sh
# Usage: generate-config.sh <output-file>
#
# Writes the runtime configuration (config.js) from CONDUCTOR_UI_* variables
# at container start, so one build serves any deployment:
#
#   CONDUCTOR_UI_CONDUCTOR_URL       conductor admin API (gRPC-Web); relative
#                                    URLs resolve against the page, empty
#                                    means the page's own origin
#   CONDUCTOR_UI_JOBWORKERP_SERVERS  JSON array of {name, grpcWebUrl?, adminUiUrl?}
#   CONDUCTOR_UI_CRON_TIMEZONE       IANA zone conductor interprets cron in
#   CONDUCTOR_UI_DEFAULT_LANGUAGE    ja | en
#   CONDUCTOR_UI_DEFAULT_THEME       light | dark | system
#
# Every value is emitted as a JSON string literal; nested values such as the
# server list stay strings and are parsed and validated by the app. Escaping
# is therefore the only defence needed against a value breaking out of the
# script, including "</script>". Empty variables count as unset.
#
# POSIX sh + awk only: it also runs in images without a JSON tool.
set -eu

[ $# -eq 1 ] || {
  echo "usage: $0 <output-file>" >&2
  exit 2
}
out=$1

awk '
function esc(s,    i, c, r) {
  r = ""
  for (i = 1; i <= length(s); i++) {
    c = substr(s, i, 1)
    if (c == "\\") r = r "\\\\"
    else if (c == "\"") r = r "\\\""
    else if (c in ctrl) r = r ctrl[c]
    else if (c == "<") r = r "\\u003c"
    else if (c == ">") r = r "\\u003e"
    else if (c == "&") r = r "\\u0026"
    else r = r c
  }
  return r
}
BEGIN {
  for (i = 1; i < 32; i++) ctrl[sprintf("%c", i)] = sprintf("\\u%04x", i)
  ctrl[sprintf("%c", 127)] = "\\u007f"
  n = split("conductorUrl=CONDUCTOR_UI_CONDUCTOR_URL " \
            "jobworkerpServers=CONDUCTOR_UI_JOBWORKERP_SERVERS " \
            "cronTimezone=CONDUCTOR_UI_CRON_TIMEZONE " \
            "defaultLanguage=CONDUCTOR_UI_DEFAULT_LANGUAGE " \
            "defaultTheme=CONDUCTOR_UI_DEFAULT_THEME", pairs, " ")
  body = ""
  for (i = 1; i <= n; i++) {
    split(pairs[i], kv, "=")
    v = ENVIRON[kv[2]]
    if (v == "") continue
    body = body (body == "" ? "" : ", ") "\"" kv[1] "\": \"" esc(v) "\""
  }
  print "// Generated by generate-config.sh at container start; do not edit."
  print "window.__CONDUCTOR_UI_CONFIG__ = {" body "};"
}' >"${out}.tmp"
mv "${out}.tmp" "${out}"
